"""A Simple TokenizerV2 which handles "unknown" words
"""

class SimpleTokenizerV2:


    def __init__(self, upd_vocab):
      self.str_to_int = upd_vocab
      self.int_to_str = {v: k for k, v in self.str_to_int.items()}

    def encode(self, vocab):
      # We update the regex to capture the special tokens whole: (<\|endoftext\|>|<\|eos\|>|<\|unk\|>)
      preprocessed = re.split(r'(<\|endoftext\|>|<\|eos\|>|<\|unk\|>|[,.:;?_!"()\']|--|\s)', vocab)
      preprocessed = [
          item.strip() for item in preprocessed if item.strip()
          ]
      preprocessed = [item if item in self.str_to_int else "<|unk|>" for item in preprocessed]
      ids = [self.str_to_int[item] for item in preprocessed]
      return ids

    def decode(self, ids):
      text = " ".join([self.int_to_str[i] for i in ids])
      # Replace spaces before the specified punctuations
      text = re.sub(r'\s+([,.:;?!"()\'])', r'\1', text)
      return text

