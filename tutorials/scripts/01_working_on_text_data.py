# @title Coding Dataset Class and DataLoader

import torch
from torch.utils.data import Dataset, DataLoader

class GPTDatasetV1(Dataset):
  """
  A custom PyTorch Dataset that prepares tokenized text into input-target chunk pairs
  using a sliding window approach for training Autoregressive Language Models (like GPT).
  """

  def __init__(self, txt, tokenizer, max_length, stride):
    """
    Initializes the dataset by tokenizing the input text and sliding a window over it
    to create input chunks (x) and target chunks (y) shifted by one token.

    Args:
        txt (str): The raw input text document.
        tokenizer (tiktoken.Encoding): The Byte-Pair-Encoding tokenizer used to encode text.
        max_length (int): The sequence length (context size) of each training sample.
        stride (int): The distance the sliding window shifts at each step.
    """
    # Two empty lists are initialized to store the chunks of input data and their corresponding shifted targets.
    self.input_ids = []
    self.target_ids = []

    # Tokenizing the entire input text into a flat list of token IDs.
    # The parameter allowed_special={"<|endoftext|"} allows processing specific special end-of-text markers if present.
    token_ids = tokenizer.encode(txt, allowed_special={"<|endoftext|"})

    # Safety check: ensure we have enough tokens to form at least one full input (max_length) and target (shifted by 1) slice.
    assert len(token_ids) > max_length, "Number of tokenized inputs must at least be equal to max_length+1"

    # Slide a window across the tokens to generate overlapping chunk pairs.
    for i in range(0, len(token_ids) - max_length, stride):
      input_chunk = token_ids[i : i + max_length]
      # Target chunk is the exact same window, but shifted forward by 1 token to predict the next word
      target_chunk = token_ids[i + 1 : i + max_length + 1]

      # Store both chunks as PyTorch Tensors
      self.input_ids.append(torch.tensor(input_chunk))
      self.target_ids.append(torch.tensor(target_chunk))

  def __len__(self):
    """
    Returns the total number of sliding window samples generated.
    """
    return len(self.input_ids)

  def __getitem__(self, idx):
    """
    Retrieves a single training pair (input_chunk, target_chunk) at the specified index.
    """
    return self.input_ids[idx], self.target_ids[idx]

# @title defining Build_DataLoaderV1 function to build Pytorch based Data Loader
def Build_DataLoaderV1(txt,
                       batch_size=4,
                       max_length=256,
                       stride=128,
                       shuffle=True,
                       drop_last=True,
                       num_workers=0
                       ):
  """
  Constructs and returns a PyTorch DataLoader for tokenized text inputs using a sliding window.

  Args:
      txt (str): The raw text sequence to tokenize and load.
      batch_size (int): Number of text sequences grouped together in each batch. Defaults to 4.
      max_length (int): Maximum sequence length (context window) for inputs and targets. Defaults to 256.
      stride (int): Step size to slide the context window across the tokenized text. Defaults to 128.
      shuffle (bool): If True, shuffles the dataset batches before each training epoch. Defaults to True.
      drop_last (bool): If True, discards the last batch if its size is smaller than batch_size. Defaults to True.
      num_workers (int): Number of subprocesses to use for data loading. Defaults to 0.

  Returns:
      DataLoader: A PyTorch DataLoader iterator yielding (input_batch, target_batch) token ID pairs.
  """
  # Load the standard GPT-2 byte-pair encoding (BPE) tokenizer
  tokenizer = tiktoken.get_encoding("gpt2")

  # Initialize the dataset which handles tokenization and sliding window division
  dataset = GPTDatasetV1(txt, tokenizer, max_length, stride)

  # Package the dataset into a PyTorch DataLoader configuration
  dataloader = DataLoader(
      dataset,
      batch_size=batch_size,
      shuffle=shuffle,
      drop_last=drop_last,
      num_workers=num_workers
      )

  return dataloader

