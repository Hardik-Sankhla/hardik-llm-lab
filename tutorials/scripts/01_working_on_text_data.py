import textwrap

# Function to Wrap text by converting list to string
def printWT(label, data, width=80):
    """Converts the data list/object to a string and wraps the text smoothly across lines."""
    print(label)
    wrapped_text = textwrap.fill(str(data), width=width)
    print(wrapped_text)
    print("-" * width)

# Function to Wrap Long Lists without losing the list structure representation
def printWL(label, items, width=80):
    """Wraps long lists by appending items and managing line breaks without exceeding the width."""
    print(label)
    if not items:
        print("[]")
        print("-" * width)
        return

    lines = []
    current_line = "["

    for i, item in enumerate(items):
        formatted_item = repr(item)
        is_last = (i == len(items) - 1)

        # Prepare what we want to append
        suffix = "" if is_last else ", "
        item_str = formatted_item + suffix

        # If adding this item to the current line exceeds width (excluding the final closed bracket)
        # and the current line isn't just the starting bracket
        if len(current_line) + len(item_str) > (width - 1 if is_last else width) and current_line != "[":
            lines.append(current_line)
            current_line = " " + item_str
        else:
            current_line += item_str

    if current_line:
        current_line += "]"
        lines.append(current_line)

    for line in lines:
        print(line)
    print("-" * width)

# Function to wrap and format as a Python Dictionary { key: value }
def printWD(label, dictionary, width=80, max_items=None):
    """Wraps and formats a dictionary as a string, keeping lines within the maximum width.
    Optionally limits the print output to the first max_items if specified.
    """
    print(label)

    current_line = "{"
    items = list(dictionary.items())
    if max_items is not len(items) and max_items is not None:
        items = items[:max_items]

    for i, (key, value) in enumerate(items):
        entry = f"{repr(key)}: {repr(value)}"
        if i < len(items) - 1:
            entry += ", "

        if len(current_line) + len(entry) > width - 1:
            print(current_line)
            current_line = "  " + entry
        else:
            current_line += entry

    if current_line:
        closing = "}" if max_items is None or len(dictionary) <= max_items else "...}"
        print(current_line.rstrip(", ") + closing)
    print("-" * width)

# Function to display a dictionary in a clean, column-aligned table
def printDT(label, dictionary, max_key_len=20, max_val_len=50):
    """Prints a dictionary as an aligned key-value table, truncating long items."""
    print(label)
    print(f"{'KEY':<{max_key_len}} | {'VALUE':<{max_val_len}}")
    print("-" * (max_key_len + max_val_len + 3))

    for key, value in dictionary.items():
        k_str = str(key)[:max_key_len - 3] + "..." if len(str(key)) > max_key_len else str(key)
        v_str = str(value)[:max_val_len - 3] + "..." if len(str(value)) > max_val_len else str(value)
        print(f"{k_str:<{max_key_len}} | {v_str:<{max_val_len}}")

