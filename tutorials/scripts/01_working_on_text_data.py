class SimpleTokenizerV1:

    def __init__(self, vocab):
      self.str_to_int = vocab
      self.int_to_str = {v: k for k, v in self.str_to_int.items()}



    def encode(self, vocab):
      preprocessed = re.split(r'([,.:;?_!"()\']|--|\s)', vocab)
      preprocessed = [
          word.strip() for word in preprocessed if word.strip()
          ]
      ids= [self.str_to_int[word] for word in preprocessed]
      return ids

    def decode(self, ids):
      text = " ".join([self.int_to_str[i] for i in ids])
      text = re.sub(r'\s+([,.?!"()\'])', r'\1', text)
      return text

